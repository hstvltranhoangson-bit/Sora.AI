// Quy ước xưng hô nhất quán trong giao diện, hoạt ảnh và lời thông báo:
// người dùng = anh, nhân vật Sora = em. Giữ nguyên mã khóa và {biến}.
function loiThoaiAnhEm(value) {
  if (Array.isArray(value)) return value.map(loiThoaiAnhEm);
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, loiThoaiAnhEm(item)]));
  }
  if (typeof value !== 'string') return value;
  return value
    .replace(/Chúng mình/g, 'Anh và em')
    .replace(/chúng mình/g, 'anh và em')
    .replace(/Sơn ơi/g, 'Anh ơi')
    .replace(/Sơn/g, 'anh')
    .replace(/Cậu/g, 'Anh')
    .replace(/cậu/g, 'anh')
    .replace(/Mình/g, 'Em')
    .replace(/mình/g, 'em');
}

